import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const DEDICATED_DIR = path.join(__dirname, '../src/components/dedicated');
const PRIMITIVES_FILE = path.join(__dirname, '../src/components/primitives/LayoutPrimitives.tsx');
const OUTPUT_FILE = path.join(__dirname, '../src/components/registry.ts');

// Component sources define where components are discovered and how they are imported.
const COMPONENT_SOURCES = [
    {
        name: 'PRIMITIVE_COMPONENTS',
        getComponents: () => getFileComponents(PRIMITIVES_FILE),
        generateImport: components =>
            `import { ${components.join(', ')} } from './primitives/LayoutPrimitives';`
    },
    {
        name: 'DEDICATED_COMPONENTS',
        getComponents: () => getDirectoryComponents(DEDICATED_DIR),
        generateImport: components =>
            components.map(component =>
                `import { ${component} } from './dedicated/${component}';`
            ).join('\n')
    }
];

// Discover components exported as individual .tsx files.
function getDirectoryComponents(directory) {
    if (!fs.existsSync(directory)) {
        throw new Error(`Components directory not found: ${directory}`);
    }

    return fs.readdirSync(directory, { withFileTypes: true })
        .filter(entry => entry.isFile() && entry.name.startsWith('Ui') && entry.name.endsWith('.tsx'))
        .map(entry => path.basename(entry.name, '.tsx'))
        .sort();
}

// Discover components exported from a single TypeScript file.
function getFileComponents(file) {
    if (!fs.existsSync(file)) {
        throw new Error(`Components file not found: ${file}`);
    }

    const content = fs.readFileSync(file, 'utf8');

    return [...content.matchAll(/export\s+function\s+(Ui[A-Za-z0-9]+)/g)]
        .map(match => match[1])
        .sort();
}

// Generate the component registry object.
function generateRegistry(components) {
    return [
        'export const COMPONENT_REGISTRY: Record<string, React.ComponentType<any>> = {',
        components.map(component => `  ${component},`).join('\n').replace(/,$/, ''),
        '};',
        ''
    ].join('\n');
}

// Generate a component name array.
function generateComponentArray(name, components) {
    return [
        `export const ${name} = [`,
        components.map(component => `  '${component}',`).join('\n').replace(/,$/, ''),
        '];',
        ''
    ].join('\n');
}

// Resolve all configured component sources.
const sources = COMPONENT_SOURCES.map(source => ({
    ...source,
    components: source.getComponents()
}));

// Keep the registry order defined by COMPONENT_SOURCES.
const allComponents = sources.flatMap(source => source.components);

// Generate component imports.
const imports = [
    "import React from 'react';",
    ...sources.map(source => source.generateImport(source.components))
];

// Generate registry file content.
const content = [
    '// This file is auto-generated by scripts/build-registry.js',
    '// Do not edit this file manually.',
    '',
    ...imports,
    '',
    generateRegistry(allComponents),
    ...sources.map(source => generateComponentArray(source.name, source.components))
].join('\n');

// Avoid unnecessary filesystem writes when the registry is already up to date.
if (fs.existsSync(OUTPUT_FILE) && fs.readFileSync(OUTPUT_FILE, 'utf8') === content) {
    console.log('Registry is already up to date.');
    process.exit(0);
}

fs.writeFileSync(OUTPUT_FILE, content, 'utf8');

console.log(`Successfully generated src/components/registry.ts (${allComponents.length} components)`);
