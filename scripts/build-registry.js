import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const DEDICATED_DIR = path.join(__dirname, '../src/components/dedicated');
const PRIMITIVES_FILE = path.join(__dirname, '../src/components/primitives/LayoutPrimitives.tsx');
const OUTPUT_FILE = path.join(__dirname, '../src/components/registry.ts');

// 1. Scan dedicated components in src/components/dedicated
const dedicatedFiles = fs.readdirSync(DEDICATED_DIR);
const dedicatedComponents = [];
for (const file of dedicatedFiles) {
  if (file.startsWith('Ui') && file.endsWith('.tsx')) {
    const compName = path.basename(file, '.tsx');
    dedicatedComponents.push(compName);
  }
}
dedicatedComponents.sort();

// 2. Scan primitive components in src/components/primitives/LayoutPrimitives.tsx
const primitivesContent = fs.readFileSync(PRIMITIVES_FILE, 'utf-8');
const primitiveMatches = primitivesContent.match(/export\s+function\s+(Ui[A-Za-z0-9]+)/g) || [];
const primitiveComponents = primitiveMatches.map(m => {
  const match = m.match(/export\s+function\s+(Ui[A-Za-z0-9]+)/);
  return match ? match[1] : null;
}).filter(Boolean);
primitiveComponents.sort();

// 3. Generate registry file content
let content = `// This file is auto-generated by scripts/build-registry.js
// Do not edit this file manually.

import React from 'react';
`;

// Add imports for dedicated components
for (const comp of dedicatedComponents) {
  content += `import { ${comp} } from './dedicated/${comp}';\n`;
}

// Add imports for primitive components
content += `import { ${primitiveComponents.join(', ')} } from './primitives/LayoutPrimitives';\n\n`;

// Add COMPONENT_REGISTRY
content += `export const COMPONENT_REGISTRY: Record<string, React.ComponentType<any>> = {\n`;
for (const comp of dedicatedComponents) {
  content += `  ${comp},\n`;
}
for (const comp of primitiveComponents) {
  content += `  ${comp},\n`;
}
content = content.trimEnd().replace(/,$/, '');
content += `\n};\n\n`;

// Add PRIMITIVE_COMPONENTS
content += `export const PRIMITIVE_COMPONENTS = [\n`;
for (const comp of primitiveComponents) {
  content += `  '${comp}',\n`;
}
content = content.trimEnd().replace(/,$/, '');
content += `\n];\n\n`;

// Add DEDICATED_COMPONENTS
content += `export const DEDICATED_COMPONENTS = [\n`;
for (const comp of dedicatedComponents) {
  content += `  '${comp}',\n`;
}
content = content.trimEnd().replace(/,$/, '');
content += `\n];\n`;

fs.writeFileSync(OUTPUT_FILE, content, 'utf-8');
console.log('Successfully generated src/components/registry.ts');
