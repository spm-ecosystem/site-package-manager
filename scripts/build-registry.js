import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const WEBSITES_DIR = path.join(__dirname, '../websites');
const DEDICATED_DIR = path.join(__dirname, '../src/components/dedicated');
const PRIMITIVES_FILE = path.join(__dirname, '../src/components/primitives/LayoutPrimitives.tsx');
const OUTPUT_FILE = path.join(__dirname, '../src/components/registry.ts');

// 1. Scan websites/ directory for manifest files to extract referenced components
const referencedComponents = new Set();

function scanManifests(dir) {
  if (!fs.existsSync(dir)) return;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      scanManifests(fullPath);
    } else if (entry.isFile() && entry.name === 'manifest.json') {
      try {
        const manifest = JSON.parse(fs.readFileSync(fullPath, 'utf-8'));
        if (manifest.components) {
          for (const comp of manifest.components) {
            if (comp.name) referencedComponents.add(comp.name);
          }
        }
        if (manifest.reconstructs) {
          for (const recon of manifest.reconstructs) {
            if (recon.layoutComponent) referencedComponents.add(recon.layoutComponent);
          }
        }
      } catch (err) {
        console.error(`[Build Registry] Error parsing manifest at ${fullPath}:`, err.message);
      }
    }
  }
}

console.log('[Build Registry] Scanning websites directory...');
scanManifests(WEBSITES_DIR);
console.log('[Build Registry] Referenced components found in websites manifests:', Array.from(referencedComponents));

// 2. Scan dedicated components in src/components/dedicated
const dedicatedFiles = fs.readdirSync(DEDICATED_DIR);
const dedicatedComponents = [];
for (const file of dedicatedFiles) {
  if (file.startsWith('Ui') && file.endsWith('.tsx')) {
    const compName = path.basename(file, '.tsx');
    dedicatedComponents.push(compName);
  }
}
dedicatedComponents.sort();

// 3. Scan primitive components in src/components/primitives/LayoutPrimitives.tsx
const primitivesContent = fs.readFileSync(PRIMITIVES_FILE, 'utf-8');
const primitiveMatches = primitivesContent.match(/export\s+function\s+(Ui[A-Za-z0-9]+)/g) || [];
const primitiveComponents = primitiveMatches.map(m => {
  const match = m.match(/export\s+function\s+(Ui[A-Za-z0-9]+)/);
  return match ? match[1] : null;
}).filter(Boolean);
primitiveComponents.sort();

// 4. Generate registry file content
// We will register all available dedicated components to ensure complete safety and availability.
let content = `// This file is auto-generated by scripts/build-registry.js
// Do not edit this file manually.

import React from 'react';
`;

// Add imports for dedicated components
for (const comp of dedicatedComponents) {
  content += `import { ${comp} } from './dedicated/${comp}';\n`;
}

// Add imports for primitive components
content += `import { ${primitiveComponents.join(', ')} } from './primitives/LayoutPrimitives';\n\n`;

// Add COMPONENT_REGISTRY
content += `export const COMPONENT_REGISTRY: Record<string, React.ComponentType<any>> = {\n`;
for (const comp of dedicatedComponents) {
  content += `  ${comp},\n`;
}
for (const comp of primitiveComponents) {
  content += `  ${comp},\n`;
}
// Remove trailing comma if any and close object
content = content.trimEnd().replace(/,$/, '');
content += `\n};\n\n`;

// Add PRIMITIVE_COMPONENTS
content += `export const PRIMITIVE_COMPONENTS = [\n`;
for (const comp of primitiveComponents) {
  content += `  '${comp}',\n`;
}
content = content.trimEnd().replace(/,$/, '');
content += `\n];\n\n`;

// Add DEDICATED_COMPONENTS
content += `export const DEDICATED_COMPONENTS = [\n`;
for (const comp of dedicatedComponents) {
  content += `  '${comp}',\n`;
}
content = content.trimEnd().replace(/,$/, '');
content += `\n];\n`;

fs.writeFileSync(OUTPUT_FILE, content, 'utf-8');
console.log('Successfully generated src/components/registry.ts');
